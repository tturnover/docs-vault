// Hidden and password-protected folders for the documentation vault (nginx njs).
//
// A folder is configured by a marker file ".vault" inside it (written by the editor through dufs):
//   {"hidden": true}                       -> only the editor can see / open it
//   {"salt": "<hex>", "hash": "<hex>"}     -> readers need a password (hash = sha256(salt + password))
// The marker moves together with its folder on rename/move.
//
// The editor (credentials forwarded to dufs, which rejects any wrong credentials with 401)
// sees everything; listings get annotated with vault_hidden / vault_locked.
// Anonymous readers: hidden folders don't exist (404), locked folders need an unlock cookie,
// listings / search results are filtered, ZIP of a folder containing restricted content is refused,
// listing formats that bypass the filter (?simple, ?noscript, WebDAV PROPFIND) are refused.

import fs from 'fs';
import crypto from 'crypto';

const ROOT = '/data';
const MARK = '.vault';
const SECRET_FILE = '/state/secret';   // generated by entrypoint.sh on first start
const COOKIE_AGE = 30 * 24 * 3600;
const ZIP_WALK_LIMIT = 200000;

/* ---------- helpers ---------- */

const isEditor = r => (r.variables.docs_auth_pass || '') !== '';

function segsOf(uri) { return uri.split('/').filter(s => s !== ''); }
const pathOf = segs => '/' + segs.join('/');

function parseArgs(raw) {
    const out = {};
    if (!raw) return out;
    for (const part of raw.split('&')) {
        if (!part) continue;
        const i = part.indexOf('=');
        let k = i < 0 ? part : part.slice(0, i);
        try { k = decodeURIComponent(k.replace(/\+/g, ' ')); } catch (e) { /* keep raw */ }
        out[k] = true;
    }
    return out;
}

let secretCache = null;
function secret() {
    if (secretCache === null) secretCache = fs.readFileSync(SECRET_FILE, 'utf8').trim();
    return secretCache;
}

const sha256 = s => crypto.createHash('sha256').update(s).digest('hex');
const cookieName = dir => 'vk_' + sha256(dir).slice(0, 16);
const tokenFor = (dir, m) => crypto.createHmac('sha256', secret()).update(dir + '\n' + m.hash).digest('hex').slice(0, 40);

// marker of a folder: null (none) | { hidden, salt, hash }
// Unreadable / broken marker => treated as hidden (fail closed).
function readMark(dir, cache) {
    if (cache && Object.prototype.hasOwnProperty.call(cache, dir)) return cache[dir];
    let m = null;
    let txt = null;
    try {
        txt = fs.readFileSync(ROOT + (dir === '/' ? '' : dir) + '/' + MARK, 'utf8');
    } catch (e) {
        if (e.code !== 'ENOENT' && e.code !== 'ENOTDIR') m = { hidden: true, salt: '', hash: '' };
    }
    if (txt !== null) {
        try {
            const j = JSON.parse(txt);
            const hash = typeof j.hash === 'string' ? j.hash.toLowerCase() : '';
            m = { hidden: !!j.hidden, salt: typeof j.salt === 'string' ? j.salt : '', hash };
            if (!m.hidden && !/^[0-9a-f]{64}$/.test(hash)) m = null;
        } catch (e) {
            m = { hidden: true, salt: '', hash: '' };
        }
    }
    if (cache) cache[dir] = m;
    return m;
}

const unlocked = (r, dir, m) => r.variables['cookie_' + cookieName(dir)] === tokenFor(dir, m);

// For an anonymous reader: is the folder `dir` (with marker m) closed?  'hidden' | 'locked' | ''
function closedFor(r, dir, m) {
    if (!m) return '';
    if (m.hidden) return 'hidden';
    return unlocked(r, dir, m) ? '' : 'locked';
}

// Walk the folders on the way to segs (including segs itself). First closed one decides.
function checkPath(r, segs, cache) {
    for (let i = 1; i <= segs.length; i++) {
        const dir = pathOf(segs.slice(0, i));
        const c = closedFor(r, dir, readMark(dir, cache));
        if (c) return { state: c, dir };
    }
    return null;
}

// Does the folder tree below `base` contain anything an anonymous reader may not get?
function subtreeClosed(r, base) {
    let seen = 0;
    const stack = [base];
    while (stack.length) {
        const dir = stack.pop();
        let entries;
        try { entries = fs.readdirSync(ROOT + (dir === '/' ? '' : dir), { withFileTypes: true }); }
        catch (e) { return true; }
        for (const en of entries) {
            if (++seen > ZIP_WALK_LIMIT) return true;
            if (!en.isDirectory()) continue;
            const sub = (dir === '/' ? '' : dir) + '/' + en.name;
            if (closedFor(r, sub, readMark(sub))) return true;
            stack.push(sub);
        }
    }
    return false;
}

/* ---------- access decision (js_set $vault_action) ---------- */
// 'ok'    pass through (anything unexpected, e.g. an empty value after a script error, is refused)
// 'json'  pass through the listing filter
// '403' / '404' / 'Z' (zip refused) / 'L<dir>' (locked folder)
function action(r) {
    const q = parseArgs(r.variables.args);
    const json = Object.prototype.hasOwnProperty.call(q, 'json');
    if (isEditor(r)) return json ? 'json' : 'ok';

    const m = r.method;
    if (m === 'PROPFIND' || m === 'PROPPATCH' || m === 'LOCK' || m === 'UNLOCK') return '403';
    for (const k of ['simple', 'noscript', 'token', 'tokengen']) if (Object.prototype.hasOwnProperty.call(q, k)) return '403';

    let segs;
    try { segs = segsOf(r.uri); } catch (e) { return '404'; }
    if (segs.some(s => s === MARK)) return '404';
    const c = checkPath(r, segs, {});
    if (c) return c.state === 'hidden' ? '404' : 'L' + c.dir;
    if (Object.prototype.hasOwnProperty.call(q, 'zip') && subtreeClosed(r, pathOf(segs))) return 'Z';
    return json ? 'json' : 'ok';
}

/* ---------- locked folder response (js_content) ---------- */
function encPath(p) { return p.split('/').map(encodeURIComponent).join('/'); }

function locked(r) {
    const dir = (r.variables.va || '').slice(1);   // snapshot taken in location / ($vault_action would re-run here)
    const q = parseArgs(r.variables.args);
    const nav = (r.method === 'GET' || r.method === 'HEAD') && !Object.prototype.hasOwnProperty.call(q, 'json')
        && ((r.headersIn['Sec-Fetch-Mode'] || '') === 'navigate' || /text\/html/.test(r.headersIn['Accept'] || ''));
    if (nav) {
        const uri = r.variables.vault_uri || '/';
        let isDir = uri.endsWith('/');
        if (!isDir) { try { isDir = fs.statSync(ROOT + uri).isDirectory(); } catch (e) { /* missing → file view */ } }
        if (isDir || Object.prototype.hasOwnProperty.call(q, 'view') || Object.prototype.hasOwnProperty.call(q, 'edit')) {
            r.internalRedirect('/__vault/spa');
        } else {
            r.return(302, r.variables.request_uri.split('?')[0] + '?view');
        }
        return;
    }
    r.headersOut['Content-Type'] = 'application/json';
    r.headersOut['Cache-Control'] = 'no-store';
    r.headersOut['X-Vault-Locked'] = encPath(dir);
    r.return(403, JSON.stringify({ locked: dir }));
}

/* ---------- listing filter (js_header_filter / js_body_filter) ---------- */
function jsonHeaders(r) {
    delete r.headersOut['Content-Length'];
    r.headersOut['Cache-Control'] = 'no-store';
}

// Response chunks are kept per request: with the QuickJS engine module-level variables
// survive between requests, so nothing request-specific may live there.
const pending = new Map();   // connection:request -> Buffer[]
function jsonBody(r, data, flags) {
    const id = r.variables.connection + ':' + r.variables.connection_requests;   // $request_id is not stable across filter calls
    let chunks = pending.get(id);
    if (!chunks) { chunks = []; pending.set(id, chunks); }
    if (data && data.length) chunks.push(typeof data === 'string' ? Buffer.from(data) : data);
    if (!flags.last) return;
    pending.delete(id);
    if (pending.size > 64) pending.clear();   // leftovers of aborted responses
    const raw = Buffer.concat(chunks);
    if (r.status !== 200) { r.sendBuffer(raw, flags); return; }
    let out;
    try {
        out = JSON.stringify(filterListing(r, JSON.parse(raw.toString())));
    } catch (e) {
        // not a listing (e.g. ?json on a file): access to the path itself was already allowed
        r.sendBuffer(raw, flags);
        return;
    }
    r.sendBuffer(out, flags);
}

function filterListing(r, data) {
    if (!data || !Array.isArray(data.paths)) return data;
    const editor = isEditor(r);
    const base = segsOf(r.variables.vault_uri || '/');
    const cache = {};
    const self = readMark(pathOf(base), cache);
    if (base.length && self) data.vault_self = { hidden: self.hidden, locked: !self.hidden && !!self.hash };
    data.paths = data.paths.filter(p => {
        const rel = String(p.name || '').split('/').filter(s => s !== '');
        if (!rel.length || rel.some(s => s === MARK)) return false;
        const isDir = /Dir/.test(String(p.path_type || ''));
        // folders strictly between the listed folder and the item
        for (let i = 1; i < rel.length; i++) {
            const dir = pathOf(base.concat(rel.slice(0, i)));
            const m = readMark(dir, cache);
            if (!editor && closedFor(r, dir, m)) return false;
        }
        if (isDir) {
            const dir = pathOf(base.concat(rel));
            const m = readMark(dir, cache);
            if (m) {
                if (m.hidden) {
                    if (!editor) return false;
                    p.vault_hidden = true;
                } else {
                    p.vault_locked = true;
                    if (!editor) p.vault_open = unlocked(r, dir, m);
                }
            }
        }
        return true;
    });
    return data;
}

/* ---------- unlock (POST /__vault/unlock  {path, password}) ---------- */
function unlock(r) {
    const send = (code, obj) => {
        r.headersOut['Content-Type'] = 'application/json';
        r.headersOut['Cache-Control'] = 'no-store';
        r.return(code, JSON.stringify(obj));
    };
    if (r.method !== 'POST') return send(405, { ok: false });
    let body;
    try { body = JSON.parse(r.requestText || ''); } catch (e) { return send(400, { ok: false }); }
    const segs = segsOf(String(body.path || ''));
    const pw = String(body.password || '');
    if (!segs.length || segs.some(s => s === '.' || s === '..' || s === MARK)) return send(400, { ok: false });
    const dir = pathOf(segs);
    const cache = {};
    // everything above must be reachable already (no probing of hidden folders)
    const above = checkPath(r, segs.slice(0, -1), cache);
    if (above) return send(above.state === 'hidden' ? 404 : 403, above.state === 'hidden' ? { ok: false } : { ok: false, locked: above.dir });
    const m = readMark(dir, cache);
    if (!m || m.hidden) return send(404, { ok: false });
    if (sha256(m.salt + pw) !== m.hash) return send(403, { ok: false, wrong: true });
    const https = (r.headersIn['X-Forwarded-Proto'] || '') === 'https';
    r.headersOut['Set-Cookie'] = cookieName(dir) + '=' + tokenFor(dir, m) + '; Path=/; Max-Age=' + COOKIE_AGE
        + '; HttpOnly; SameSite=Lax' + (https ? '; Secure' : '');
    send(200, { ok: true });
}

// forget all unlocked folders (POST /__vault/lock)
function lockAll(r) {
    const names = Object.keys(r.headersIn['Cookie'] ? parseCookies(r.headersIn['Cookie']) : {}).filter(n => /^vk_[0-9a-f]{16}$/.test(n));
    if (names.length) r.headersOut['Set-Cookie'] = names.map(n => n + '=; Path=/; Max-Age=0; HttpOnly; SameSite=Lax');
    r.headersOut['Content-Type'] = 'application/json';
    r.return(200, JSON.stringify({ ok: true, n: names.length }));
}
function parseCookies(h) {
    const out = {};
    h.split(';').forEach(p => { const i = p.indexOf('='); if (i > 0) out[p.slice(0, i).trim()] = p.slice(i + 1).trim(); });
    return out;
}

export default { action, locked, jsonHeaders, jsonBody, unlock, lockAll };
